const locked = new Set(["slug", "disclaimer"]);

function blobUrl(value) {
  const raw = String(value ?? "").trim();
  try {
    const url = new URL(raw);
    if (url.protocol === "https:" && url.hostname.endsWith(".public.blob.vercel-storage.com")) return url.toString();
  } catch {
    return "";
  }
  return "";
}

function pageImage(value, fallback) {
  const hosted = blobUrl(value);
  if (hosted) return hosted;
  const raw = String(value ?? "").trim();
  if (!raw) return fallback;
  let url;
  try {
    url = new URL(raw, "https://itg.local");
  } catch {
    return fallback;
  }
  if (url.origin !== "https://itg.local") return fallback;
  if (!/^\/images\/[a-z0-9/-]+\.(jpg|jpeg|png|webp)$/.test(url.pathname)) return fallback;
  const version = url.searchParams.get("v");
  if (url.search && (!/^\d+$/.test(version || "") || [...url.searchParams.keys()].some((key) => key !== "v"))) {
    return fallback;
  }
  return version ? `${url.pathname}?v=${version}` : url.pathname;
}

function footerLogoPath(value, fallback) {
  const hosted = blobUrl(value);
  if (hosted) return hosted;
  const raw = String(value ?? "").trim();
  if (!raw) return fallback;
  let url;
  try {
    url = new URL(raw, "https://itg.local");
  } catch {
    return fallback;
  }
  if (url.origin !== "https://itg.local" || url.search) return fallback;
  if (!/^\/logo\/ANIMATIONS\/[a-zA-Z0-9][a-zA-Z0-9._-]*\.svg$/.test(url.pathname)) return fallback;
  return url.pathname;
}

function cleanString(value, fallback) {
  const limit = Math.max(fallback.length, fallback.length > 80 ? 2000 : 240);
  const cleaned = String(value ?? "").trim();
  if (!cleaned) return fallback;
  return cleaned.slice(0, limit);
}

function mergeEntries(input, fallback) {
  if (!Array.isArray(input)) return Array.isArray(fallback) ? fallback : [];
  return input
    .slice(0, 80)
    .map((entry) => ({
      term: plainText(entry && entry.term, 120),
      definition: plainText(entry && entry.definition, 700),
    }))
    .filter((entry) => entry.term || entry.definition);
}

function mergeShape(fallback, input, key) {
  if (key === "entries") return mergeEntries(input, fallback);
  if (key === "image" && typeof fallback === "string") return pageImage(input, fallback);
  if (key === "footerLogo" && typeof fallback === "string") return footerLogoPath(input, fallback);
  if (typeof fallback === "string") return cleanString(input, fallback);
  if (typeof fallback === "boolean" || typeof fallback === "number") return fallback;
  if (Array.isArray(fallback)) {
    const source = Array.isArray(input) ? input : [];
    return fallback.map((item, index) => mergeShape(item, source[index]));
  }
  if (fallback && typeof fallback === "object") {
    const source = input && typeof input === "object" ? input : {};
    const out = {};
    for (const child of Object.keys(fallback)) {
      out[child] = locked.has(child) ? fallback[child] : mergeShape(fallback[child], source[child], child);
    }
    return out;
  }
  return fallback;
}

function plainText(value, limit) {
  return String(value ?? "").replace(/\s+/g, " ").trim().slice(0, limit);
}

function personImage(value) {
  return pageImage(value, "");
}

function mergeTeam(input) {
  const fallback = pageCopy.team;
  const source = input && typeof input === "object" ? input : {};
  const people = Array.isArray(source.people) ? source.people : [];
  return {
    eyebrow: cleanString(source.eyebrow, fallback.eyebrow),
    title: cleanString(source.title, fallback.title),
    lede: cleanString(source.lede, fallback.lede),
    people: people
      .slice(0, 24)
      .map((person) => ({
        name: plainText(person && person.name, 80),
        role: plainText(person && person.role, 80),
        excerpt: plainText(person && person.excerpt, 400),
        image: personImage(person && person.image),
      }))
      .filter((person) => person.name || person.role || person.excerpt || person.image),
  };
}

function phoneText(value, fallback) {
  const text = plainText(value, 40);
  const digits = text.replace(/\D/g, "");
  if (digits.length < 10 || digits.length > 15) return fallback;
  return text;
}

function emailText(value, fallback) {
  const text = plainText(value, 120);
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(text)) return fallback;
  return text;
}

function coord(value, fallback) {
  const text = plainText(value, 24);
  if (!/^-?\d+(\.\d+)?$/.test(text)) return fallback;
  const number = Number(text);
  if (number < -180 || number > 180) return fallback;
  return text;
}

function mergeOffice(input) {
  const fallback = pageCopy.office;
  const source = input && typeof input === "object" ? input : {};
  return {
    phone: phoneText(source.phone, fallback.phone),
    fax: phoneText(source.fax, fallback.fax),
    street: plainText(source.street, 120) || fallback.street,
    city: plainText(source.city, 80) || fallback.city,
    region: plainText(source.region, 40) || fallback.region,
    postalCode: plainText(source.postalCode, 20) || fallback.postalCode,
    emailGeneral: emailText(source.emailGeneral, fallback.emailGeneral),
    emailOrders: emailText(source.emailOrders, fallback.emailOrders),
    emailPostClosing: emailText(source.emailPostClosing, fallback.emailPostClosing),
    emailPreCd: emailText(source.emailPreCd, fallback.emailPreCd),
    emailProcessing: emailText(source.emailProcessing, fallback.emailProcessing),
    emailEvents: emailText(source.emailEvents, fallback.emailEvents),
    lat: coord(source.lat, fallback.lat),
    lon: coord(source.lon, fallback.lon),
    placeId: placeIdText(source.placeId),
  };
}

function placeIdText(value) {
  const text = plainText(value, 200);
  if (!text) return "";
  if (!/^[A-Za-z0-9_-]+$/.test(text)) return "";
  return text;
}

function mergePage(id, input) {
  if (id === "team") return mergeTeam(input);
  if (id === "office") return mergeOffice(input);
  const fallback = pageCopy[id];
  if (!fallback) return null;
  return mergeShape(fallback, input);
}

function mergePages(input) {
  const source = input && typeof input === "object" ? input : {};
  const pages = {};
  for (const id of Object.keys(pageCopy)) pages[id] = mergePage(id, source[id]);
  return pages;
}

